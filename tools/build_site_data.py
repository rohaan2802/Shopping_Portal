"""Bundle webpage data so index.html works from file:// as well as over HTTP.

    python tools/build_site_data.py

Browsers block fetch() of local JSON when a page is opened by double-clicking it,
so this script:
  1. writes assets/js/data.js  (window.SHOP_DATA = {catalog, screenshots})
  2. rewrites the screenshot gallery inside index.html between the
     <!-- GALLERY:START --> and <!-- GALLERY:END --> markers as plain <img> tags.
record_evidence.py and render_figures.py call it automatically.
"""

from pathlib import Path
from html import escape
import json, re

ROOT = Path(__file__).resolve().parents[1]


def main():
    catalog = json.loads((ROOT / "reports/catalog.json").read_text(encoding="utf-8"))
    shots = json.loads((ROOT / "assets/screenshots/manifest.json").read_text(encoding="utf-8"))
    payload = json.dumps({"catalog": catalog, "screenshots": shots}, separators=(",", ":"), ensure_ascii=False)
    (ROOT / "assets/js/data.js").write_text(
        "// Generated by tools/build_site_data.py from reports/catalog.json and\n"
        "// assets/screenshots/manifest.json. Do not edit by hand.\n"
        f"window.SHOP_DATA = {payload};\n",
        encoding="utf-8", newline="\n")

    cards = []
    for i, f in enumerate(shots):
        t, c, cap, src = (escape(f[k]) for k in ("title", "category", "caption", "source"))
        cards.append(
            f'      <figure class="shot" data-category="{c}" data-index="{i}">\n'
            f'        <button type="button" aria-label="Open screenshot {f["number"]}: {t}">'
            f'<img src="{f["image"]}" alt="{f["number"]}. {t}" width="1600" height="1000" loading="lazy" decoding="async"></button>\n'
            f'        <figcaption><span class="tag">{c}</span><b>{f["number"]}. {t}</b><span>{cap}</span><small>Source: {src}</small></figcaption>\n'
            f'      </figure>')
    page = (ROOT / "index.html").read_text(encoding="utf-8")
    block = "<!-- GALLERY:START -->\n" + "\n".join(cards) + "\n      <!-- GALLERY:END -->"
    page, n = re.subn(r"<!-- GALLERY:START -->.*?<!-- GALLERY:END -->", lambda m: block, page, flags=re.S)
    if n != 1:
        raise SystemExit("index.html is missing the GALLERY markers")
    (ROOT / "index.html").write_text(page, encoding="utf-8", newline="\n")
    print(f"assets/js/data.js: {len(catalog['products'])} products, {len(shots)} screenshots; gallery updated in index.html")


if __name__ == "__main__":
    main()
