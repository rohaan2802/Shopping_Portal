// Shopping_Portal webpage: theme, navigation, insights, screenshot gallery and a
// browser-only checkout sandbox. Nothing here writes native files or takes payments.
'use strict';
const $ = s => document.querySelector(s);
const $$ = s => [...document.querySelectorAll(s)];
const esc = s => String(s).replace(/[&<>"']/g, c => ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'}[c]));
const stored = (k, d) => { try { return JSON.parse(localStorage.getItem(k)) ?? d; } catch { return d; } };
const save = (k, v) => { try { localStorage.setItem(k, JSON.stringify(v)); } catch {} };
const reduceMotion = matchMedia('(prefers-reduced-motion: reduce)').matches;
const money = paisa => 'PKR ' + (paisa / 100).toLocaleString('en-US', {minimumFractionDigits: 2, maximumFractionDigits: 2});
const halfUp = (amount, basisPoints) => Math.floor((amount * basisPoints + 5000) / 10000);

/* ---------------- theme ---------------- */
function applyTheme(t) {
  document.documentElement.dataset.theme = t;
  $('#theme').setAttribute('aria-label', t === 'dark' ? 'Switch to light theme' : 'Switch to dark theme');
  document.querySelector('meta[name="theme-color"]').content = t === 'dark' ? '#0b1020' : '#4f46e5';
  save('shop-theme', t);
}
applyTheme(document.documentElement.dataset.theme === 'dark' ? 'dark' : 'light');
$('#theme').addEventListener('click', () => applyTheme(document.documentElement.dataset.theme === 'dark' ? 'light' : 'dark'));

/* ---------------- navigation ---------------- */
const nav = $('#navigation'), menu = $('#menu');
function setMenu(open) {
  nav.classList.toggle('open', open);
  menu.setAttribute('aria-expanded', String(open));
  menu.setAttribute('aria-label', open ? 'Close navigation' : 'Open navigation');
}
menu.addEventListener('click', () => setMenu(!nav.classList.contains('open')));
$$('#navigation a').forEach(a => a.addEventListener('click', () => setMenu(false)));
document.addEventListener('keydown', e => { if (e.key === 'Escape') setMenu(false); });
document.addEventListener('click', e => { if (nav.classList.contains('open') && !e.target.closest('.nav')) setMenu(false); });

function onScroll() {
  const links = $$('#navigation a'), offset = $('#header').offsetHeight + 60;
  let current = links[0];
  for (const a of links) { const t = document.querySelector(a.hash); if (t && t.getBoundingClientRect().top <= offset) current = a; }
  if (innerHeight + scrollY >= document.documentElement.scrollHeight - 4) current = links.at(-1);
  links.forEach(a => { a.classList.toggle('active', a === current); a === current ? a.setAttribute('aria-current', 'location') : a.removeAttribute('aria-current'); });
  const max = document.documentElement.scrollHeight - innerHeight, ratio = max > 0 ? scrollY / max : 0;
  $('#progressBar').style.width = (ratio * 100).toFixed(1) + '%';
  $('#top').hidden = scrollY < 500;
  $('#top').style.setProperty('--dash', String(100 - ratio * 100));
}
addEventListener('scroll', onScroll, {passive: true});
addEventListener('resize', () => { if (innerWidth > 1560) setMenu(false); onScroll(); });
$('#top').addEventListener('click', () => scrollTo({top: 0, behavior: reduceMotion ? 'auto' : 'smooth'}));
onScroll();

/* ---------------- screenshot gallery ----------------
   The <figure> cards are plain HTML in index.html (generated by tools/build_site_data.py),
   so images show even with JavaScript disabled or when the page is opened from file://. */
const DATA = window.SHOP_DATA || {catalog: {products: []}, screenshots: []};
const cards = $$('#gallery figure.shot');
let visible = cards, figCategory = 'All', position = 0;
const figureInfo = card => {
  const meta = DATA.screenshots[+card.dataset.index] || {};
  const img = card.querySelector('img');
  return {
    title: meta.number ? `${meta.number}. ${meta.title}` : card.querySelector('b').textContent,
    caption: meta.caption || card.querySelector('figcaption span:not(.tag)')?.textContent || '',
    source: meta.source || '',
    image: img.getAttribute('src')
  };
};
function filterGallery() {
  const q = $('#figureSearch').value.trim().toLowerCase();
  visible = cards.filter(c => (figCategory === 'All' || c.dataset.category === figCategory) && c.textContent.toLowerCase().includes(q));
  cards.forEach(c => { c.hidden = !visible.includes(c); });
  $('#galleryCount').textContent = visible.length === cards.length ? `${cards.length} screenshots` : `${visible.length} of ${cards.length} screenshots`;
  let empty = $('#galleryEmpty');
  if (!visible.length && !empty) { empty = document.createElement('p'); empty.id = 'galleryEmpty'; empty.className = 'muted'; empty.textContent = 'No screenshots match that search.'; $('#gallery').append(empty); }
  if (empty) empty.hidden = visible.length > 0;
}
function showFigure() {
  const f = figureInfo(visible[position]);
  $('#viewerTitle').textContent = f.title;
  $('#viewerImage').src = f.image;
  $('#viewerImage').alt = f.title;
  $('#viewerImage').classList.remove('enlarged');
  $('#zoom').setAttribute('aria-pressed', 'false');
  $('#viewerCaption').textContent = f.source ? `${f.caption}  Source: ${f.source}` : f.caption;
  $('#previous').disabled = position === 0;
  $('#next').disabled = position === visible.length - 1;
}
function openViewer(card) {
  position = Math.max(0, visible.indexOf(card));
  showFigure();
  const dialog = $('#viewer');
  if (typeof dialog.showModal === 'function') dialog.showModal(); else window.open(figureInfo(card).image, '_blank');
}
cards.forEach(c => c.querySelector('button').addEventListener('click', () => openViewer(c)));
const step = d => { const n = position + d; if (n >= 0 && n < visible.length) { position = n; showFigure(); } };
$('#previous').addEventListener('click', () => step(-1));
$('#next').addEventListener('click', () => step(1));
$('#close').addEventListener('click', () => $('#viewer').close());
$('#zoom').addEventListener('click', () => $('#zoom').setAttribute('aria-pressed', String($('#viewerImage').classList.toggle('enlarged'))));
$('#viewer').addEventListener('keydown', e => { if (e.key === 'ArrowRight') step(1); if (e.key === 'ArrowLeft') step(-1); });
$('#viewer').addEventListener('click', e => { if (e.target === $('#viewer')) $('#viewer').close(); });
let touchX = 0;
$('#viewerImage').addEventListener('touchstart', e => { touchX = e.changedTouches[0].clientX; }, {passive: true});
$('#viewerImage').addEventListener('touchend', e => { const d = e.changedTouches[0].clientX - touchX; if (Math.abs(d) > 50) step(d < 0 ? 1 : -1); }, {passive: true});
$('#figureSearch').addEventListener('input', filterGallery);
$('#filters').innerHTML = ['All', ...new Set(cards.map(c => c.dataset.category))].map(c => `<button type="button" class="chip" aria-pressed="${c === 'All'}">${esc(c)}</button>`).join('');
$$('#filters .chip').forEach(b => b.addEventListener('click', () => {
  figCategory = b.textContent;
  $$('#filters .chip').forEach(x => x.setAttribute('aria-pressed', String(x === b)));
  filterGallery();
}));
filterGallery();

/* ---------------- insights + sandbox (window.SHOP_DATA.catalog) ---------------- */
const COUPONS = {ROHAAN10: 1000, FAST5: 500};
let products = [], cart = [], stock = {}, receipt = null, coupon = null, orderNo = 1;
const available = p => stock[p.id] ?? p.stock;
const persist = () => save('shop-sandbox-v3', {cart, stock, receipt, coupon, orderNo});

function renderInsights() {
  const groups = {};
  let units = 0, value = 0;
  for (const p of products) {
    const g = groups[p.category] ??= {count: 0, value: 0};
    g.count++; g.value += p.price_paisa * p.stock; units += p.stock; value += p.price_paisa * p.stock;
  }
  const low = products.filter(p => p.stock <= 5);
  const restock = products.reduce((s, p) => s + Math.max(0, 10 - p.stock) * p.price_paisa, 0);
  $('#kpis').innerHTML = [
    [products.length.toLocaleString('en-US'), 'products'],
    [units.toLocaleString('en-US'), 'stock units'],
    [money(value), 'inventory value'],
    [low.length, 'low-stock items (≤ 5)']
  ].map(([b, s]) => `<div class="kpi"><b>${b}</b><span>${s}</span></div>`).join('') +
    `<div class="kpi" style="grid-column:1/-1"><b>${money(restock)}</b><span>estimated cost to restock every product to 10 units</span></div>`;
  const rows = Object.entries(groups).sort((a, b) => b[1].value - a[1].value), max = rows[0]?.[1].value || 1;
  $('#valueBars').innerHTML = rows.map(([name, g]) => `<div class="bar"><span>${esc(name)}</span><div class="track"><div class="fill" style="width:${(g.value / max * 100).toFixed(1)}%"></div></div><span class="v">${(g.value / 100).toLocaleString('en-US', {maximumFractionDigits: 0})}</span></div>`).join('');
  const byCat = {};
  for (const p of products) (byCat[p.category] ??= []).push(p.price_paisa);
  const statRow = (name, prices) => {
    const v = [...prices].sort((a, b) => a - b), n = v.length, mid = Math.floor(n / 2);
    const half = (num, d) => Math.floor((num + Math.floor(d / 2)) / d);
    const median = n % 2 ? v[mid] : half(v[mid - 1] + v[mid], 2), mean = half(v.reduce((a, b) => a + b, 0), n);
    const f = x => (x / 100).toLocaleString('en-US', {minimumFractionDigits: 2, maximumFractionDigits: 2});
    return `<tr><td>${esc(name)}</td><td>${n}</td><td>${f(v[0])}</td><td>${f(median)}</td><td>${f(mean)}</td><td>${f(v[n - 1])}</td></tr>`;
  };
  $('#priceStats').innerHTML = Object.keys(byCat).sort().map(c => statRow(c, byCat[c])).join('') +
    statRow('All categories', products.map(p => p.price_paisa)).replace('<tr>', '<tr class="total">');
  $('#lowStock').innerHTML = [...low].sort((a, b) => a.stock - b.stock || a.name.localeCompare(b.name)).slice(0, 10)
    .map(p => `<tr><td>${esc(p.name)}</td><td>${esc(p.category)}</td><td class="stock-low">${p.stock}</td></tr>`).join('');
}

function renderProducts() {
  const q = $('#productSearch').value.trim().toLowerCase(), c = $('#productCategory').value, s = $('#productSort').value, only = $('#inStock').checked;
  const list = products.filter(p => p.name.toLowerCase().includes(q) && (!c || p.category === c) && (!only || available(p) > 0));
  list.sort((a, b) => s === 'price' ? a.price_paisa - b.price_paisa : s === 'price-desc' ? b.price_paisa - a.price_paisa : s === 'stock' ? available(a) - available(b) : a.name.localeCompare(b.name));
  $('#productCount').textContent = `${list.length} matching products${list.length > 12 ? ' · first 12 shown' : ''}`;
  $('#products').innerHTML = list.slice(0, 12).map(p => {
    const n = available(p), out = n < 1;
    return `<article class="card product"><span class="pill">${esc(p.category)}</span><h3>${esc(p.name)}</h3><div class="price">${money(p.price_paisa)}</div><p class="muted ${n <= 5 ? 'stock-low' : ''}">${out ? 'Out of stock' : n + ' in stock'}</p><div class="row"><input class="qty" type="number" min="1" max="${n}" value="1" aria-label="Quantity for ${esc(p.name)}" ${out ? 'disabled' : ''}><button type="button" class="btn btn-primary" data-add="${p.id}" ${out ? 'disabled' : ''}>Add</button></div></article>`;
  }).join('') || '<p class="muted">No products match these filters.</p>';
  $$('[data-add]').forEach(b => b.addEventListener('click', () => addToCart(b.dataset.add, Number(b.parentElement.querySelector('input').value))));
}

function addToCart(id, n) {
  const p = products.find(x => x.id === id), line = cart.find(x => x.id === id), have = line?.qty ?? 0;
  if (!Number.isInteger(n) || n < 1 || n + have > available(p)) { $('#demoMessage').textContent = `Enter a whole quantity within available stock (${available(p) - have} left for ${p.name}).`; return; }
  line ? line.qty += n : cart.push({id, qty: n});
  $('#demoMessage').textContent = `Added ${n} × ${p.name}. Stock changes only on checkout.`;
  persist(); renderCart();
}

function bill() {
  const gross = cart.reduce((s, l) => s + products.find(p => p.id === l.id).price_paisa * l.qty, 0);
  const discount = coupon ? halfUp(gross, COUPONS[coupon]) : 0, subtotal = gross - discount;
  const tax = halfUp(subtotal, 500), delivery = halfUp(subtotal, 500);
  return {gross, discount, subtotal, tax, delivery, total: subtotal + tax + delivery};
}

function renderCart() {
  $('#cartCount').textContent = cart.reduce((s, l) => s + l.qty, 0);
  $('#cartLines').innerHTML = cart.length ? cart.map(l => {
    const p = products.find(x => x.id === l.id);
    return `<div class="cartline"><span><strong>${esc(p.name)}</strong><br><span class="muted">${l.qty} × ${money(p.price_paisa)}</span></span><span class="stepper"><button type="button" data-dec="${p.id}" aria-label="One less ${esc(p.name)}">−</button><button type="button" data-inc="${p.id}" aria-label="One more ${esc(p.name)}">+</button><button type="button" data-remove="${p.id}" aria-label="Remove ${esc(p.name)}">✕</button></span></div>`;
  }).join('') : '<p class="muted">Your cart is empty. Add a product to begin.</p>';
  const b = bill();
  const rows = [['Gross', b.gross]];
  if (b.discount) rows.push([`Discount ${coupon} (${COUPONS[coupon] / 100}%)`, -b.discount, 'discount']);
  rows.push(['Subtotal', b.subtotal], ['Tax · 5%', b.tax], ['Delivery · 5%', b.delivery], ['Total', b.total, 'total']);
  $('#bill').innerHTML = rows.map(([label, v, cls = '']) => `<div class="billrow ${cls}"><span>${esc(label)}</span><span>${v < 0 ? '− ' + money(-v) : money(v)}</span></div>`).join('');
  $('#checkout').disabled = !cart.length;
  $$('[data-inc]').forEach(x => x.addEventListener('click', () => addToCart(x.dataset.inc, 1)));
  $$('[data-dec]').forEach(x => x.addEventListener('click', () => { const l = cart.find(c => c.id === x.dataset.dec); l.qty--; cart = cart.filter(c => c.qty > 0); persist(); renderCart(); }));
  $$('[data-remove]').forEach(x => x.addEventListener('click', () => { cart = cart.filter(c => c.id !== x.dataset.remove); persist(); renderCart(); }));
  $('#receipt').textContent = receipt || 'A simulated receipt appears here after checkout.';
}

$('#couponForm').addEventListener('submit', e => {
  e.preventDefault();
  const code = $('#coupon').value.trim().toUpperCase();
  if (!code) { coupon = null; $('#demoMessage').textContent = 'Discount removed.'; }
  else if (COUPONS[code]) { coupon = code; $('#demoMessage').textContent = `${code} applied: ${COUPONS[code] / 100}% off before tax and delivery.`; }
  else { $('#demoMessage').textContent = `Code "${code}" is not valid. Try ROHAAN10.`; return; }
  persist(); renderCart();
});

$('#checkout').addEventListener('click', () => {
  if (!cart.length) return;
  if (cart.some(l => l.qty > available(products.find(p => p.id === l.id)))) { $('#demoMessage').textContent = 'Stock changed. Reset the sandbox and try again.'; return; }
  const b = bill(), pad = (s, n) => String(s).padEnd(n), lpad = (s, n) => String(s).padStart(n);
  const lines = cart.map(l => { const p = products.find(x => x.id === l.id); stock[p.id] = available(p) - l.qty; return `${pad(l.qty + ' × ' + p.name, 28)}${lpad(money(p.price_paisa * l.qty), 16)}`; });
  const row = (k, v) => `${pad(k, 28)}${lpad(v, 16)}`;
  receipt = [`SIMULATED RECEIPT #SB-${String(orderNo++).padStart(4, '0')}  (browser only)`, '-'.repeat(44), ...lines, '-'.repeat(44), row('Gross', money(b.gross)),
    ...(b.discount ? [row(`Discount ${coupon}`, '− ' + money(b.discount))] : []), row('Subtotal', money(b.subtotal)), row('Tax 5%', money(b.tax)), row('Delivery 5%', money(b.delivery)), row('TOTAL', money(b.total)), '-'.repeat(44), 'No payment taken. Native data files unchanged.'].join('\n');
  cart = []; coupon = null; $('#coupon').value = '';
  persist(); renderProducts(); renderCart();
  $('#demoMessage').textContent = 'Simulated order complete. See the receipt below.';
});

$('#resetDemo').addEventListener('click', () => {
  cart = []; stock = {}; receipt = null; coupon = null; orderNo = 1; $('#coupon').value = '';
  persist(); renderProducts(); renderCart();
  $('#demoMessage').textContent = 'Sandbox reset to the sample catalog.';
});
['#productSearch', '#productCategory', '#productSort', '#inStock'].forEach(s => $(s).addEventListener(s === '#productSearch' ? 'input' : 'change', renderProducts));

function initCatalog(data) {
  products = (data.products || []).map((p, i) => ({...p, id: String(i)}));
  if (!products.length) {
    $('#kpis').innerHTML = '<p class="muted">Catalog data is missing. Run <code>python tools/build_site_data.py</code> to regenerate assets/js/data.js.</p>';
    return;
  }
  const state = stored('shop-sandbox-v3', {});
  if (state && typeof state === 'object') {
    if (state.stock && typeof state.stock === 'object') for (const p of products) { const n = state.stock[p.id]; if (Number.isInteger(n) && n >= 0 && n <= p.stock) stock[p.id] = n; }
    cart = Array.isArray(state.cart) ? state.cart.filter(l => l && products.some(p => p.id === l.id) && Number.isInteger(l.qty) && l.qty > 0) : [];
    receipt = typeof state.receipt === 'string' ? state.receipt : null;
    coupon = COUPONS[state.coupon] ? state.coupon : null;
    orderNo = Number.isInteger(state.orderNo) && state.orderNo > 0 ? state.orderNo : 1;
  }
  $('#productCategory').innerHTML = '<option value="">All categories</option>' + [...new Set(products.map(p => p.category))].sort().map(c => `<option>${esc(c)}</option>`).join('');
  renderInsights(); renderProducts(); renderCart();
}
initCatalog(DATA.catalog || {});
